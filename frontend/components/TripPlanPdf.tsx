function MarkdownBlocks({ children }: { children: React.ReactNode }) {
  return <View>{children}</View>;
}

export function TripPlanPDF({
  title,
  answer,
}: {
  title: string;
  answer: string;
}) {
  return (
    <Document title={title} author="TripSync">
      <Page size="A4" style={styles.page} wrap>
        <Text style={styles.title} wrap={true}>
          {title}
        </Text>
        <Text style={styles.subtitle}>
          Your personalized itinerary · Generated by TripSync
        </Text>

        <ReactMarkdown
          remarkPlugins={[remarkGfm]}
          components={{
            h1: ({ children }) =>
              createElement(Text, { style: styles.heading1 }, children),
            h2: ({ children }) =>
              createElement(Text, { style: styles.heading2 }, children),
            h3: ({ children }) =>
              createElement(Text, { style: styles.heading3 }, children),
            p: ({ children }) =>
              createElement(Text, { style: styles.paragraph }, children),
            strong: ({ children }) =>
              createElement(
                Text,
                { style: { fontFamily: "Helvetica-Bold" } },
                children,
              ),
            em: ({ children }) =>
              createElement(
                Text,
                { style: { fontFamily: "Helvetica-Oblique" } },
                children,
              ),
            a: ({ href, children }) =>
              createElement(
                Link,
                { src: href || "", style: styles.link },
                children,
              ),
            ul: ({ children }) =>
              createElement(View, { style: styles.list }, children),
            ol: ({ children }) =>
              createElement(View, { style: styles.list }, children),
            li: ({ children, node }) => {
              const parent = node?.position ? node : undefined;

              const isOrdered =
                parent?.tagName === "li" && node?.position !== undefined;

              return createElement(
                View,
                { style: styles.listItem },
                createElement(Text, { style: styles.bullet }, "•"),
                createElement(Text, { style: styles.listText }, children),
              );
            },
            blockquote: ({ children }) =>
              createElement(View, { style: styles.quote }, children),
            code: ({ children }) =>
              createElement(Text, { style: styles.code }, children),
            pre: ({ children }) =>
              createElement(View, { style: styles.code }, children),
            hr: () =>
              createElement(View, {
                style: {
                  borderBottomWidth: 1,
                  borderBottomColor: "#dfe6db",
                  marginVertical: 10,
                },
              }),
            table: ({ children }) =>
              createElement(View, { style: styles.table }, children),

            thead: ({ children }) =>
              createElement(View, { style: styles.tableHeaderRow }, children),

            tbody: ({ children }) => createElement(View, null, children),

            tr: ({ children }) =>
              createElement(
                View,
                { style: styles.tableRow, wrap: false },
                children,
              ),

            th: ({ children }) =>
              createElement(Text, { style: styles.tableHeaderCell }, children),

            td: ({ children }) =>
              createElement(Text, { style: styles.tableCell }, children),
          }}
        >
          {answer}
        </ReactMarkdown>

        <Text
          fixed
          style={styles.footer}
          render={({ pageNumber, totalPages }) =>
            `TripSync  •  Page ${pageNumber} of ${totalPages}`
          }
        />
      </Page>
    </Document>
  );
}
